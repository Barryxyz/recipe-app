-- F0.3: per-user tables (DESIGN §5).
-- IDs default to gen_random_uuid() but clients may supply their own (offline creation, F3.6).
-- ingredient_id columns are soft references (not foreign keys) into catalog.ingredients or
-- app.ingredients_private, so the two schemas stay independent (D1).

-- v1: every user gets a personal household. It exists now so household sharing needs no
-- data migration later. Rows are created by the sign-up trigger (F0.2).
create table app.households (
  id         uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table app.users (
  id                   uuid primary key references auth.users on delete cascade,
  household_id         uuid not null references app.households,
  purchase_verified_at timestamptz,   -- App Store proof checked (NFR-8, F0.6); service role only
  purchase_environment text check (purchase_environment in ('Production', 'Sandbox', 'Xcode')),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  deleted_at           timestamptz
);
create index users_household_id_idx on app.users (household_id);

-- The caller's household. Security definer so RLS policies can call it without
-- needing (and recursing through) the policies on app.users.
create function app.current_household_id()
returns uuid
language sql
stable
security definer
set search_path = ''
as $$
  select household_id from app.users where id = auth.uid() and deleted_at is null
$$;

create table app.user_prefs (
  user_id               uuid primary key default auth.uid() references app.users on delete cascade,
  diets                 text[] not null default '{}',
  allergens             text[] not null default '{}',
  staple_ingredient_ids bigint[] not null default '{}',  -- always treated as available
  default_servings      int not null default 2 check (default_servings between 1 and 20),
  updated_at            timestamptz not null default now()
);

-- "Customizable expiry": per ingredient type and location (F1.6).
create table app.user_shelf_life_overrides (
  user_id       uuid not null default auth.uid() references app.users on delete cascade,
  ingredient_id bigint not null,
  location      text not null check (location in ('fridge', 'freezer', 'pantry')),
  days          int not null check (days >= 0),
  updated_at    timestamptz not null default now(),
  deleted_at    timestamptz,
  primary key (user_id, ingredient_id, location)
);

-- Items the catalog doesn't know. IDs start at 1e12 so a soft-referenced ingredient_id
-- can never collide with a catalog.ingredients id.
create table app.ingredients_private (
  id                 bigint generated by default as identity (start with 1000000000000) primary key,
  user_id            uuid not null default auth.uid() references app.users on delete cascade,
  name               text not null,
  nutrients_per_100g jsonb,               -- null until estimated (§6.1b, F2.3)
  is_estimated       boolean not null default true,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  deleted_at         timestamptz,
  constraint ingredients_private_id_range check (id >= 1000000000000)
);
create index ingredients_private_user_id_idx on app.ingredients_private (user_id);

create table app.pantry_items (
  id                uuid primary key default gen_random_uuid(),
  household_id      uuid not null default app.current_household_id() references app.households on delete cascade,
  added_by          uuid default auth.uid() references app.users on delete set null,
  ingredient_id     bigint,
  display_name      text not null,
  quantity          numeric check (quantity >= 0),   -- null = "some"
  unit              text,
  location          text not null default 'fridge' check (location in ('fridge', 'freezer', 'pantry')),
  added_at          timestamptz not null default now(),
  expires_at        timestamptz,
  expiry_overridden boolean not null default false,
  status            text not null default 'active' check (status in ('active', 'used', 'discarded')),
  source            text not null check (source in ('scan', 'manual', 'shopping_list')),
  updated_at        timestamptz not null default now(),
  deleted_at        timestamptz
);
create index pantry_items_household_status_expiry_idx on app.pantry_items (household_id, status, expires_at);

create table app.recipes (
  id                 uuid primary key default gen_random_uuid(),
  user_id            uuid not null default auth.uid() references app.users on delete cascade,
  title              text not null,
  description        text,
  servings           int check (servings > 0),
  prep_min           int check (prep_min >= 0),
  cook_min           int check (cook_min >= 0),
  steps              jsonb not null default '[]',   -- ordered list of instruction strings
  macros_per_serving jsonb,                         -- calculated by the server, never by the model
  macros_total       jsonb,
  source             text not null check (source in ('ai', 'edited', 'shared', 'manual')),
  model_version      text,                          -- null for manual recipes
  share_token        text unique,                   -- null = not shared
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  deleted_at         timestamptz,
  constraint recipes_steps_is_array check (jsonb_typeof(steps) = 'array'),
  constraint recipes_manual_has_no_model check (source <> 'manual' or model_version is null)
);
create index recipes_user_updated_idx on app.recipes (user_id, updated_at desc);

-- Synced with the parent recipe; no updated_at/deleted_at of their own.
create table app.recipe_ingredients (
  recipe_id     uuid not null references app.recipes on delete cascade,
  position      int not null check (position >= 0),
  ingredient_id bigint,                 -- null if free text
  name          text not null,          -- copied so the recipe still reads correctly
  quantity      numeric check (quantity >= 0),
  unit          text,
  grams         numeric check (grams >= 0),
  note          text,
  is_optional   boolean not null default false,
  primary key (recipe_id, position)
);

create table app.shopping_list_items (
  id               uuid primary key default gen_random_uuid(),
  household_id     uuid not null default app.current_household_id() references app.households on delete cascade,
  ingredient_id    bigint,
  name             text not null,
  quantity         numeric check (quantity >= 0),
  unit             text,
  source_recipe_id uuid references app.recipes on delete set null,
  checked          boolean not null default false,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  deleted_at       timestamptz
);
create index shopping_list_items_household_checked_idx on app.shopping_list_items (household_id, checked);

-- AI cost visibility (D5). Written only by Edge Functions with the service role.
create table app.ai_usage_log (
  id            bigint generated always as identity primary key,
  user_id       uuid references app.users on delete set null,
  kind          text not null,                    -- 'scan' | 'recipes' | 'nutrition' | ...; free text so test calls (F0.5) can log too
  model         text not null,
  input_tokens  int not null check (input_tokens >= 0),
  output_tokens int not null check (output_tokens >= 0),
  created_at    timestamptz not null default now()
);
create index ai_usage_log_user_created_idx on app.ai_usage_log (user_id, created_at);

