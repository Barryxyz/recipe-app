-- F0.3: shared ingredient catalog (DESIGN §5). Seeded by F0.4.

create table catalog.ingredients (
  id                      bigint generated by default as identity primary key,
  name                    text not null,
  aliases                 text[] not null default '{}',   -- "scallion", "green onion"
  category                text,                           -- produce, dairy, meat, ...
  fdc_id                  int,                            -- USDA FoodData Central id
  default_unit            text,                           -- "g", "ml", "each"
  grams_per_unit          numeric check (grams_per_unit > 0),     -- 1 egg ≈ 50 g
  density_g_per_ml        numeric check (density_g_per_ml > 0),
  shelf_life_fridge_days  int check (shelf_life_fridge_days >= 0),
  shelf_life_freezer_days int check (shelf_life_freezer_days >= 0),
  shelf_life_pantry_days  int check (shelf_life_pantry_days >= 0),
  is_common_staple        boolean not null default false, -- salt, oil, pepper
  allergens               text[] not null default '{}'    -- top-9 allergens + gluten; checked in code
);

comment on table catalog.ingredients is 'Shared ingredient catalog. Read-only to users; written by migrations/seed or the service role.';

-- Nutrition per 100 g, from USDA FoodData Central. One row per ingredient.
create table catalog.ingredient_nutrients (
  ingredient_id bigint primary key references catalog.ingredients on delete cascade,
  kcal      numeric check (kcal >= 0),
  protein_g numeric check (protein_g >= 0),
  carbs_g   numeric check (carbs_g >= 0),
  fat_g     numeric check (fat_g >= 0),
  fiber_g   numeric check (fiber_g >= 0),
  sugar_g   numeric check (sugar_g >= 0),
  sodium_mg numeric check (sodium_mg >= 0)
);

-- Fuzzy name search (pg_trgm). A trigram index can't cover a text[] directly, so
-- aliases are indexed through an immutable function that joins them into one string.
-- Queries must call catalog.aliases_text(aliases) to use the index.
create function catalog.aliases_text(aliases text[])
returns text
language sql
immutable
parallel safe
set search_path = ''
as $$ select coalesce(array_to_string(aliases, ' '), '') $$;

create index ingredients_name_trgm_idx
  on catalog.ingredients using gin (name extensions.gin_trgm_ops);
create index ingredients_aliases_trgm_idx
  on catalog.ingredients using gin (catalog.aliases_text(aliases) extensions.gin_trgm_ops);

-- Read for every signed-in user; no client writes.
alter table catalog.ingredients          enable row level security;
alter table catalog.ingredient_nutrients enable row level security;

create policy "catalog is readable by signed-in users"
  on catalog.ingredients for select to authenticated using (true);
create policy "catalog is readable by signed-in users"
  on catalog.ingredient_nutrients for select to authenticated using (true);

grant select on all tables in schema catalog to authenticated;
grant execute on function catalog.aliases_text(text[]) to authenticated;
grant all on all tables in schema catalog to service_role;
grant usage, select on all sequences in schema catalog to service_role;
